def _field_json_schema(block_type: str, cfg: Any) -> dict[str, Any] | None:
    """Map one Block.schema item to a JSON-schema fragment for tool calling."""

    def get(key: str, default: Any = None) -> Any:
        try:
            return cfg.get(key, default)
        except AttributeError:
            return default

    schema: dict[str, Any] | None = None

    if block_type in _SCALAR_FIELD_SCHEMAS:
        schema = dict(_SCALAR_FIELD_SCHEMAS[block_type])
        if get("max_length"):
            schema["maxLength"] = get("max_length")
        if get("min_value") is not None:
            schema["minimum"] = get("min_value")
        if get("max_value") is not None:
            schema["maximum"] = get("max_value")
        if block_type == "regex_field" and get("regex"):
            schema["pattern"] = get("regex")

    elif block_type in ("choice_field", "multiple_choice_field"):
        choices = [str(c.get("value")) for c in (get("choices") or []) if c.get("value")]
        labels = ", ".join(f"{c.get('value')} ({c.get('label')})" for c in (get("choices") or []) if c.get("value"))
        item = {"type": "string"}
        if choices:
            item["enum"] = choices
        if block_type == "multiple_choice_field":
            schema = {"type": "array", "items": item}
        else:
            schema = item
        if labels:
            schema["description"] = f"Choices: {labels}"

    elif block_type in _CHOOSER_FIELD_TARGETS:
        target = _CHOOSER_FIELD_TARGETS[block_type]
        if block_type == "snippet_chooser_field" and get("target_model"):
            target = f"{get('target_model')} snippet"
        schema = {
            "type": "integer",
            "description": (
                f"Database ID of an existing {target}. Discover valid IDs with the relevant list/search tools."
            ),
        }

    elif block_type == "list_field":
        inner_items = get("blocks") or []
        child_schema: dict[str, Any] = {"type": "string"}
        if inner_items:
            child = _field_json_schema(inner_items[0].block_type, inner_items[0].value)
            if child:
                child_schema = child
        schema = {"type": "array", "items": child_schema}

    elif block_type in ("struct", "list_struct"):
        properties: dict[str, Any] = {}
        required: list[str] = []
        for item in get("blocks") or []:
            name = item.value.get("name", "unnamed")
            child = _field_json_schema(item.block_type, item.value)
            if child is None:
                continue
            properties[name] = child
            if item.value.get("required", True):
                required.append(name)
        obj: dict[str, Any] = {"type": "object", "properties": properties}
        if required:
            obj["required"] = required
        schema = {"type": "array", "items": obj} if block_type == "list_struct" else obj

    elif block_type == "stream":
        allowed = [item.value.get("name", "unnamed") for item in (get("blocks") or [])]
        schema = {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "type": {"type": "string", "enum": allowed} if allowed else {"type": "string"},
                    "value": {"type": "object"},
                },
                "required": ["type", "value"],
            },
            "description": f"Mixed content stream. Allowed types: {', '.join(allowed)}",
        }

    if schema is None:
        return None

    if block_type in ("list_field", "list_struct", "stream"):
        if get("min_num") is not None:
            schema["minItems"] = get("min_num")
        if get("max_num") is not None:
            schema["maxItems"] = get("max_num")

    help_text = get("help_text")
    if help_text:
        existing = schema.get("description")
        schema["description"] = f"{help_text} ({existing})" if existing else help_text

    return schema


def block_value_json_schema(block) -> dict[str, Any]:
    """Generate the JSON schema of a Block's ``value`` from its stored schema."""
    properties: dict[str, Any] = {}
    required: list[str] = []
    for item in block.schema:
        name = item.value.get("name", "unnamed")
        field_schema = _field_json_schema(item.block_type, item.value)
        if field_schema is None:
            continue
        properties[name] = field_schema
        if item.value.get("required", True):
            required.append(name)
    schema: dict[str, Any] = {"type": "object", "properties": properties}
    if required:
        schema["required"] = required
    return schema


