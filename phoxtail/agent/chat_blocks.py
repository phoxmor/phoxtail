_STOP_WORDS = frozenset("a an and are as at be by for from in into is it of on or that the this to with".split())


def _search_blocks(query: str):
    """Rank chat-eligible Block rows for a query via the Wagtail search backend.

    The Postgres backend ANDs all terms, so a natural-language shape query
    ("breakdown of one amount into labeled parts") matches nothing as-is.
    We search the full query first, then each significant token separately
    and rank by how many tokens hit — OR semantics with relevance ordering.
    Falls back to the whole library so the agent always sees its options.
    Retrieval is deliberately swappable behind the same tool contract
    (e.g. for a vector-search backend).
    """
    from wagtail.search.backends import get_search_backend

    from phoxtail.streams.cache import get_cached_dynamic_blocks
    from phoxtail.streams.models import Block

    renderable = set(dict(get_cached_dynamic_blocks()))
    base_qs = Block.objects.filter(is_shared=False)
    backend = get_search_backend()
    query = (query or "").strip()

    scores: dict[str, float] = {}
    by_id: dict[str, Any] = {}

    def tally(hits, weight: float) -> None:
        try:
            for rank, b in enumerate(hits):
                if b.identifier not in renderable:
                    continue
                by_id[b.identifier] = b
                scores[b.identifier] = scores.get(b.identifier, 0.0) + weight - rank * 0.01
        except Exception:
            logger.warning("Block search failed for %r", query, exc_info=True)

    if query:
        tally(backend.search(query, base_qs), weight=10.0)
        tally(backend.autocomplete(query, base_qs), weight=5.0)
        tokens = [t for t in re.findall(r"[a-z0-9]+", query.lower()) if len(t) > 2 and t not in _STOP_WORDS]
        for token in tokens[:10]:
            tally(backend.search(token, base_qs), weight=1.0)

    ranked = sorted(scores, key=lambda ident: -scores[ident])
    results = [by_id[ident] for ident in ranked]
    for b in base_qs.all():  # unmatched blocks trail the ranked ones
        if b.identifier in renderable and b.identifier not in scores:
            results.append(b)
    return results


def _find_blocks_sync(query: str) -> str:
    blocks = _search_blocks(query)
    top, rest = blocks[:_FIND_BLOCKS_LIMIT], blocks[_FIND_BLOCKS_LIMIT:]
    payload = {
        "blocks": [
            {
                "identifier": b.identifier,
                "name": b.name,
                "description": b.description,
                "value_schema": block_value_json_schema(b),
            }
            for b in top
        ],
        "other_available": [{"identifier": b.identifier, "name": b.name} for b in rest],
    }
    if not payload["blocks"]:
        payload["note"] = "No blocks in the library match. Consider design_block for a custom one-off component."
    return json.dumps(payload)


async def _find_blocks(ctx: RunContext[None], query: str) -> str:
    try:
        return await sync_to_async(_find_blocks_sync)(query)
    except Exception as exc:
        logger.warning("find_blocks failed", exc_info=True)
        return json.dumps({"error": str(exc)})


async def _render_block(ctx: RunContext[None], identifier: str, value: dict) -> str:
    from django.core.exceptions import ValidationError

    dom_id = f"chat-{uuid.uuid4().hex[:12]}"
    try:
        html = await sync_to_async(render_chat_block)(identifier, value or {}, dom_id)
    except KeyError as exc:
        return json.dumps({"error": str(exc.args[0]) if exc.args else str(exc)})
    except ValidationError as exc:
        detail = getattr(exc, "message_dict", None) or getattr(exc, "messages", None) or str(exc)
        return json.dumps(
            {
                "error": "Block value failed validation. Fix the fields below and call render_block again.",
                "validation": detail if isinstance(detail, (dict, list)) else str(detail),
            },
            default=str,
        )
    except Exception as exc:
        logger.warning("render_block failed for '%s'", identifier, exc_info=True)
        return json.dumps({"error": f"Could not render block '{identifier}' ({exc}). Answer in plain text instead."})
    _pending[dom_id] = {"kind": "block_html", "html": html}
    return json.dumps(
        {
            "ok": True,
            "chat_block_id": dom_id,
            "note": ("The block is now visible to the user in the chat. Do not repeat its content in text."),
        }
    )


async def _design_block(
    ctx: RunContext[None],
    html: str,
    css: str = "",
    javascript: str = "",
    title: str = "",
) -> str:
    if not (html or "").strip():
        return json.dumps({"error": "html must not be empty."})
    dom_id = f"chat-{uuid.uuid4().hex[:12]}"
    _pending[dom_id] = {
        "kind": "block_custom",
        "html": html,
        "css": css or "",
        "javascript": javascript or "",
        "title": title or "",
    }
    return json.dumps(
        {
            "ok": True,
            "chat_block_id": dom_id,
            "note": (
                "The custom component is now visible to the user in the chat. "
                "Do not repeat its content in text. If the user asks to keep or "
                "reuse this design, create a permanent Block "
                "(phoxtail_studio_create_block) and BlockVariant "
                "(phoxtail_studio_create_variant) from it."
            ),
        }
    )


