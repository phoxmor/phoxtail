"""Chat-block rendering: the chatbot answers through the streams block system.

Architecture:

- **Discovery** — one ``find_blocks(query)`` tool searches the Block library
  (Wagtail search over name/identifier/description; ``Block.description`` is
  the human- and agent-facing "when to use me" text) and returns the top
  candidates *with their value JSON schemas inline*, generated by walking
  ``Block.schema`` — the same stored schema the Wagtail factory consumes.
- **Lane A** — ``render_block(identifier, value)`` deserializes and renders any
  discovered block through the existing streams pipeline
  (``to_python`` -> ``clean`` -> ``render``), no page involved, and streams the
  HTML to the chat pane as a ``block_html`` SSE event.
- **Lane B** — ``design_block(html, css, javascript)`` lets the agent
  invent a component on the spot. It renders inline like any block, following
  the variant-author conventions (self-scoped CSS under a unique root class,
  design tokens via CSS custom properties). Promotion to a real
  Block/BlockVariant goes through the existing studio MCP tools.

Rendered payloads are stashed out-of-band and popped by the chat stream
handler; only a small confirmation JSON travels back into the model's
context window.

BEFORE PRODUCTION — three trust decisions are deliberately deferred while the
chatbot is development-only (authenticated CMS staff, dev projects). Decide
them before the first client deployment enables the chatbot:

1. Write-tool safety: content the agent reads can steer it into mutating
   tools. The durable answer is human-in-the-loop approval on writes. Note
   that stripping write tools alone cannot enforce a readonly mode:
   design_block's JavaScript executes in the browser with the chat
   user's session and could perform writes through the HTTP API.
2. Rich text / raw HTML: LLM output landing in a ``rich_text_field`` renders
   through ``|richtext`` unsanitized — a live XSS surface. Needs sanitization
   or a curated chat-eligible flag on Block.
3. Chooser lookups: chooser fields fetch DB objects by PK inside
   ``to_python``. Today the chat endpoint's auth gate is the only check; if
   the API ever grows per-object read rules, the render path needs them too.
"""

