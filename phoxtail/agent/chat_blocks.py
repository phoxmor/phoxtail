def try_parse_partial_json(fragment: str) -> dict | None:
    """Best-effort parse of a streaming, possibly-truncated JSON object.

    Closes open strings and brackets; drops dangling members. Returns None
    when no valid object can be recovered — callers simply skip that delta.
    """
    fragment = fragment.strip()
    if not fragment.startswith("{"):
        return None
    try:
        parsed = json.loads(fragment)
        return parsed if isinstance(parsed, dict) else None
    except json.JSONDecodeError:
        pass

    stack: list[str] = []
    in_str = False
    escaped = False
    for ch in fragment:
        if in_str:
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                in_str = False
        elif ch == '"':
            in_str = True
        elif ch in "{[":
            stack.append(ch)
        elif ch in "}]" and stack:
            stack.pop()

    repaired = fragment + ('"' if in_str else "")
    closers = "".join("}" if opener == "{" else "]" for opener in reversed(stack))

    # A dangling key ("key" / "key": / trailing comma) makes the object
    # unclosable; peel trailing garbage until a candidate parses.
    for _ in range(6):
        candidate = repaired.rstrip()
        while candidate and candidate[-1] in ",:":
            candidate = candidate[:-1].rstrip()
        try:
            parsed = json.loads(candidate + closers)
            return parsed if isinstance(parsed, dict) else None
        except json.JSONDecodeError:
            # Drop what looks like a dangling key string and retry.
            if candidate.endswith('"'):
                cut = candidate.rfind('"', 0, len(candidate) - 1)
                if cut == -1:
                    return None
                repaired = candidate[:cut]
                continue
            return None
    return None


