def _strip_nulls(value: Any) -> Any:
    """Drop explicit nulls so optional fields fall back to block defaults.

    Models often send ``"value_prefix": null`` for omitted optionals;
    ``to_python`` passes None straight through and templates print "None".
    ``clean()`` normalizes this on the live path but not on replay/partials.
    """
    if isinstance(value, dict):
        return {k: _strip_nulls(v) for k, v in value.items() if v is not None}
    if isinstance(value, list):
        return [_strip_nulls(v) for v in value if v is not None]
    return value


def render_chat_block(identifier: str, value: dict, dom_id: str, validate: bool = True) -> str:
    """Render a streams block from a plain value dict, with no page involved.

    ``to_python`` is the deserializer Wagtail runs when loading a StreamField;
    ``render`` is what render_block_fragment uses for pages. The only page
    residue is the ``block`` context variable that DB-authored variant
    templates read (``block.id`` / ``block.value``) — normally supplied by the
    page template's stream loop, here by a stand-in.
    """
    from phoxtail.streams.cache import get_cached_dynamic_blocks

    blocks = dict(get_cached_dynamic_blocks())
    if identifier not in blocks:
        available = ", ".join(sorted(blocks))
        raise KeyError(f"Unknown block '{identifier}'. Available: {available}")
    block_instance = blocks[identifier]
    value = _strip_nulls(value or {})
    typed_value = block_instance.to_python(value)
    # clean() both validates and normalizes (e.g. a missing optional char
    # field deserializes as None but cleans to ""). Replay and partial
    # renders still want the normalization — they just must not fail on it.
    try:
        typed_value = block_instance.clean(typed_value)
    except Exception:
        if validate:
            raise
    stand_in = SimpleNamespace(id=dom_id, value=typed_value)
    return str(block_instance.render(typed_value, context={"block": stand_in}))


def pop_pending(chat_block_id: str) -> dict[str, Any] | None:
    return _pending.pop(chat_block_id, None)


def render_history_tool_call(tool_name: str, args: dict) -> dict[str, Any] | None:
    """Re-render a stored chat-block tool call for conversation replay.

    Deterministic: the tool call's args in ``message_history`` are the full
    source of truth, exactly as page bodies re-render from stored JSON.
    Returns a message item dict, or None when re-rendering isn't possible
    (e.g. the block was deleted since).
    """
    try:
        if tool_name == "render_block":
            html = render_chat_block(
                args["identifier"],
                args.get("value") or {},
                f"chat-{uuid.uuid4().hex[:12]}",
                validate=False,
            )
            return {"role": "assistant", "type": "block_html", "html": html}
        if tool_name == "design_block":
            return {
                "role": "assistant",
                "type": "block_custom",
                "html": args.get("html") or "",
                "css": args.get("css") or "",
                "javascript": args.get("javascript") or "",
            }
    except Exception:
        logger.warning("Could not replay chat block tool call '%s'", tool_name, exc_info=True)
    return None


